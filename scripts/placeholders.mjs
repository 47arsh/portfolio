#!/usr/bin/env node
/**
 * Tracks every {{TODO: ...}} / {{TODO_URL: ...}} value in the content file.
 *   node scripts/placeholders.mjs          -> writes PLACEHOLDERS.md
 *   node scripts/placeholders.mjs --check  -> warns during `pnpm build`
 *
 * A small TypeScript AST walk keeps field paths accurate (including array
 * indices) without adding a content schema of its own.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentPath = join(root, "src", "content", "site.ts");
const outputPath = join(root, "PLACEHOLDERS.md");
const checkOnly = process.argv.includes("--check");
const RELATIVE_CONTENT = relative(root, contentPath).split("\\").join("/");

const TODO_PATTERN = /\{\{TODO(_URL)?:\s*([\s\S]*?)\}\}/;
const GROUPS = {
  githubUsername: "Handles",
  leetcodeUsername: "Handles",
  profile: "Profile",
  featured: "Featured project — anytimedesk.in",
  shipped: "Shipped projects",
  openSource: "Open source",
  tracks: "Sound",
  log: "Build log",
  earlier: "Earlier work",
  stats: "Stats fallbacks",
  heroTrack: "Hero audio",
};

const sourceText = readFileSync(contentPath, "utf8");
const sourceFile = ts.createSourceFile(
  contentPath,
  sourceText,
  ts.ScriptTarget.Latest,
  true,
);

const entries = [];
const seen = new Set();

function keyText(name) {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name)) return name.text;
  return name.getText(sourceFile);
}

function record(path, node, kind, message) {
  const position = sourceFile.getLineAndCharacterOfPosition(
    node.getStart(sourceFile),
  );
  const line = position.line + 1;
  const id = `${path}:${line}`;
  if (seen.has(id)) return;
  seen.add(id);
  entries.push({
    path,
    line,
    kind,
    message: message.trim().replace(/\s+/g, " "),
  });
}

function visit(node, path) {
  if (ts.isSourceFile(node)) {
    for (const statement of node.statements) visit(statement, path);
    return;
  }

  if (ts.isVariableStatement(node)) {
    for (const declaration of node.declarationList.declarations) {
      visit(declaration, path);
    }
    return;
  }

  if (ts.isVariableDeclaration(node)) {
    if (!node.initializer || !ts.isIdentifier(node.name)) return;
    const name = node.name.text;
    visit(node.initializer, name === "site" ? "" : name);
    return;
  }

  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
    const match = node.text.match(TODO_PATTERN);
    if (match && path) {
      record(path, node, match[1] === "_URL" ? "URL" : "text", match[2]);
    }
    return;
  }

  if (ts.isPropertyAssignment(node)) {
    const name = keyText(node.name);
    const nextPath = path ? `${path}.${name}` : name;
    visit(node.initializer, nextPath);
    return;
  }

  if (ts.isObjectLiteralExpression(node)) {
    for (const property of node.properties) visit(property, path);
    return;
  }

  if (ts.isArrayLiteralExpression(node)) {
    node.elements.forEach((element, index) => {
      visit(element, `${path}[${index}]`);
    });
  }
}

visit(sourceFile, "");

function groupFor(path) {
  const top = path.split(".")[0].split("[")[0];
  return GROUPS[top] ?? "Other";
}

function escapeCell(value) {
  return value.replace(/\|/g, "\\|");
}

function buildMarkdown() {
  const byGroup = new Map();
  for (const entry of entries) {
    const group = groupFor(entry.path);
    if (!byGroup.has(group)) byGroup.set(group, []);
    byGroup.get(group).push(entry);
  }

  const lines = [
    "# Placeholders",
    "",
    "> Generated by `pnpm placeholders`. Do not edit by hand.",
    "",
    `All personal content lives in [\`${RELATIVE_CONTENT}\`](${RELATIVE_CONTENT}).`,
    `**${entries.length} unfilled value${entries.length === 1 ? "" : "s"}** remain.`,
    "",
    "Replace each value below in the content file, then re-run `pnpm placeholders`.",
  ];

  for (const [group, groupEntries] of byGroup) {
    lines.push("", `## ${group}`, "");
    lines.push("| Field | Line | Kind | What to provide |");
    lines.push("| --- | --: | --- | --- |");
    for (const entry of groupEntries) {
      lines.push(
        `| \`${entry.path}\` | ${entry.line} | ${entry.kind} | ${escapeCell(entry.message)} |`,
      );
    }
  }

  lines.push(
    "",
    "## Notes",
    "",
    "- `null` LeetCode fallbacks are not listed (solved, rating, streak). Set them",
    "  in `stats.leetcode` if the live endpoint is unavailable.",
    "- `heroTrack` is `null`, so the optional hero play button is hidden. Set it only",
    "  when you have a direct audio file.",
    "- Links whose URL is a placeholder render as plain text, so there are no dead links.",
    "- Re-run `pnpm placeholders` after editing the content file.",
    "",
  );

  return lines.join("\n");
}

if (checkOnly) {
  if (entries.length === 0) {
    console.log("✓ No unfilled placeholders.");
    process.exit(0);
  }

  console.warn(
    `\n⚠  ${entries.length} unfilled placeholder${entries.length === 1 ? "" : "s"} in ${RELATIVE_CONTENT}:`,
  );
  for (const entry of entries) {
    console.warn(`   ${entry.path} (line ${entry.line}): ${entry.message}`);
  }
  console.warn("   Run `pnpm placeholders` for the full checklist. Build continues.\n");
  process.exit(0);
}

writeFileSync(outputPath, buildMarkdown(), "utf8");
console.log(
  `Wrote ${relative(root, outputPath)} with ${entries.length} open placeholder${entries.length === 1 ? "" : "s"}.`,
);
